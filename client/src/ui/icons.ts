export type IconName = keyof typeof PATHS;

export const ICON_NAMES = Object.keys(PATHS) as IconName[];

/** SVG do ícone, decorativo (o texto ou `aria-label` do botão é que dá o nome). */
export function icon(name: IconName, size = 18): SVGSVGElement {
  const tpl = document.createElement('template');
  tpl.innerHTML = iconHtml(name, size);
  return tpl.content.firstElementChild as SVGSVGElement;
}

/** O mesmo ícone como texto HTML (para `innerHTML` de botões montados de uma vez). */
export function iconHtml(name: IconName, size = 18): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="icon icon-${name}" aria-hidden="true" focusable="false">${PATHS[name]}</svg>`;
}

/** Troca o conteúdo de `el` pelo ícone. */
export function setIcon(el: Element, name: IconName, size?: number): void {
  el.replaceChildren(icon(name, size));
}
